/**
 * Coherent kart categories, so the editor cannot be used to build a machine
 * that does not exist — 80 hp paired with an 82 km/h top speed was the failure
 * mode these replace.
 *
 * Power and class minimum weight are published figures (Rotax and IAME
 * datasheets, Motorsport UK 2026 yearbook, CIK-FIA technical regulations for
 * Superkart). Top speeds are engineering estimates, and every grip and braking
 * value is an estimate: nobody publishes them. Single-speed karts brake on the
 * rear axle only, which is why their braking sits well below their cornering
 * grip; KZ and Superkart add front brakes and close that gap.
 *
 * These want a review against the current season's regulations before anyone
 * treats them as authoritative. See docs/PHYSICS.md.
 */
